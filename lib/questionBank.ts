// 안부 질문 표 — 어르신께 무엇을 묻는지는 전부 이 파일이 정한다.
//
// 예전에는 지병 목록만 주고 AI(Gemini)에게 "질문 6~8개 만들어 줘"라고 맡겼다. 그 결과:
//  - 개수가 날마다 달랐다(3~8개). AI가 실패하면 고정 문항 3개 + 지병당 1개로 떨어져서,
//    같은 어르신이 어제는 7개, 오늘은 4개를 받았다.
//  - 실패가 잦았다(10/28~11/11 생성의 61%). 실패한 날은 표현 2~3개가 사흘 주기로 돌아
//    "매일 똑같은 질문"이라는 말이 체험에서 나왔다.
//  - 질문이 날마다 다르면 어제와 오늘의 위험도를 같은 잣대로 견줄 수 없다.
// 그래서 질문은 사람이 정한 표에 고정하고, 코드가 이 표에서 고른다(lib/dailyQuestions.ts).
// 근거: 2회차 기술 멘토링(2026-11-12) — "질문 수와 범위는 사람이 정하기".
//
// 이 파일은 서버(api/, lib/)와 화면(demo/v1/src)이 같이 쓴다. 표를 두 군데에 베껴 두면
// 한쪽만 고쳐져 서로 다른 질문이 나가므로 한 곳에만 둔다. 그래서 다른 파일을 가져오지
// 않는 순수한 데이터로만 적는다.
//
// ── 표를 고칠 때 ───────────────────────────────────────────────
//  - id는 바꾸지 않는다. 답변 기록이 이 id로 남는다.
//  - 표현(variants)은 같은 뜻을 다르게 말한 것이다. 뜻이 달라지면 새 항목으로 만든다.
//  - 선택지는 표현마다 말만 다르고 순서와 severity는 같게 둔다
//    (ok = 걱정 없음, warn = 확인 필요, danger = 많이 걱정됨).
//  - severity는 위험도 점수가 된다(lib/riskScoring.ts: warn 1점, danger 2점, 1점부터 "위험").
//    warn을 하나 붙이면 그 답을 고른 날 보호자 화면이 "위험"이 된다는 뜻이다.
//
// ⚠️ 공통 질문과 처음 8개 지병 질문은 아직 초안이다. 앞쪽 표현은 예전 고정 문항 그대로이고,
// 나머지 표현과 '돌아가는 질문'은 새로 쓴 것이다. 골다공증·눈·신장·난청 질문은 공공 자료를
// 근거로 새로 넣었다(아래 3번 주석). 나머지도 근거가 모이면 같은 방식으로 바꾼다.

export type Category = "medication" | "meal" | "outing" | "mood" | "condition" | "other";
export type Severity = "ok" | "warn" | "danger";

export interface QuestionOption {
  text: string;
  severity: Severity;
}

export interface QuestionVariant {
  question: string;
  options: QuestionOption[];
}

export interface BankItem {
  id: string;
  category: Category;
  variants: QuestionVariant[];
}

export interface ConditionItem extends BankItem {
  /** 이 질문이 붙는 지병 — elder_condition.condition_type 값 */
  condition: string;
}

export interface RotatingItem extends BankItem {
  /** 이 지병이 있으면 이 주제는 건너뛴다 — 지병 질문이 같은 것을 이미 묻기 때문 */
  skipWith?: string[];
}

// 표현 하나를 짧게 적기 위한 도우미. 선택지는 [문장, severity] 순서쌍으로 적는다.
function v(question: string, ...options: [string, Severity][]): QuestionVariant {
  return { question, options: options.map(([text, severity]) => ({ text, severity })) };
}

